async function createDesktopFixture() {
  const root = await tempDir('factory desktop fixture % ');
  const appRoot = path.join(root, 'portable app');
  const scripts = path.join(appRoot, 'scripts');
  const resources = path.join(appRoot, 'resources');
  const state = path.join(root, 'state');
  const home = path.join(root, 'home');
  const config = path.join(root, 'config');
  const data = path.join(root, 'data');
  const bin = path.join(root, 'bin');
  await mkdir(appRoot, { recursive: true });
  await Promise.all([
    mkdir(scripts, { recursive: true }),
    mkdir(resources),
    mkdir(home),
    mkdir(config),
    mkdir(data),
    mkdir(bin),
  ]);
  await writeFile(path.join(appRoot, 'factory-desktop'), 'synthetic executable');
  await writeFile(path.join(appRoot, 'launch.sh'), '#!/bin/sh\nexit 0\n');
  await writeFile(path.join(appRoot, 'launch-test.sh'), '#!/bin/sh\nexit 0\n');
  await writeFile(path.join(resources, 'protocol-scheme'), 'factory-test\n');
  await writeFile(path.join(resources, 'factory-desktop.png'), 'synthetic icon');
  await writeFile(path.join(scripts, 'desktop-integration.py'), await readFile(path.join(repoRoot, 'scripts', 'desktop-integration.py')));
  await writeFile(path.join(scripts, 'install-desktop.sh'), await readFile(path.join(repoRoot, 'scripts', 'install-desktop.sh')));
  await writeFile(path.join(scripts, 'rollback-desktop.sh'), await readFile(path.join(repoRoot, 'scripts', 'rollback-desktop.sh')));
  await chmod(path.join(scripts, 'install-desktop.sh'), 0o755);
  await chmod(path.join(scripts, 'rollback-desktop.sh'), 0o755);
  await chmod(path.join(appRoot, 'factory-desktop'), 0o755);
  await chmod(path.join(appRoot, 'launch.sh'), 0o755);
  await chmod(path.join(appRoot, 'launch-test.sh'), 0o755);
  const xdgMime = path.join(bin, 'xdg-mime');
  await writeFile(xdgMime, `#!/usr/bin/env python3
import os, pathlib, re, sys
cmd, *args = sys.argv[1:]
home = pathlib.Path(os.environ['HOME'])
config = pathlib.Path(os.environ['XDG_CONFIG_HOME'])
data = pathlib.Path(os.environ['XDG_DATA_HOME'])
desktops = os.environ['XDG_CURRENT_DESKTOP'].lower().split(':')
mime = args[-1] if args else ''
paths = []
for name in ['mimeapps.list'] + [f'{item}-mimeapps.list' for item in desktops]:
    paths += [config / name, data / 'applications' / name]
def lookup():
    for file in paths:
        if not file.exists(): continue
        section = ''
        for line in file.read_text().splitlines():
            if line.startswith('['): section = line.strip()
            elif section == '[Default Applications]' and '=' in line:
                key, value = line.split('=', 1)
                if key.strip() == mime: return value.strip().split(';')[0]
    return ''
if cmd == 'query' and args[0] == 'default':
    print(lookup() or ('factory-desktop-linux.desktop'
        if (data / 'applications' / 'factory-desktop-linux.desktop').exists() else ''))
elif cmd == 'default':
    app, mime = args
    for file in paths:
        file.parent.mkdir(parents=True, exist_ok=True)
        lines = file.read_text().splitlines() if file.exists() else []
        section = ''
        found = False
        result = []
        for line in lines:
            if line.startswith('['): section = line.strip()
            if section == '[Default Applications]' and line.startswith(mime + '='):
                if not found: result.append(mime + '=' + app + ';'); found = True
            else: result.append(line)
        if not found:
            if '[Default Applications]' not in result: result += ['', '[Default Applications]']
            result.append(mime + '=' + app + ';')
        file.write_text('\\n'.join(result) + '\\n')
else:
    sys.exit(2)
`);
  await chmod(xdgMime, 0o755);
  const env = {
    ...process.env,
    HOME: home,
    XDG_CONFIG_HOME: config,
    XDG_DATA_HOME: data,
    XDG_STATE_HOME: state,
    XDG_CURRENT_DESKTOP: 'GNOME:KDE',
    PATH: `${bin}${path.delimiter}${process.env.PATH}`,
  };
  return { root, appRoot, env };
}

