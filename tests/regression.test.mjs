test('archive extraction preserves ordinary files and rejects unsafe paths and links', async () => {
  const root = await tempDir();
  try {
    const source = path.join(root, 'archive source');
    await mkdir(path.join(source, 'resources'), { recursive: true });
    await writeFile(path.join(source, 'resources', 'app.asar'), 'synthetic app payload');
    const archive = path.join(root, 'installer fixture.zip');
    const zip = spawnSync('zip', ['-q', '-r', archive, 'resources'], { cwd: source });
    assert.equal(zip.status, 0, zip.stderr?.toString());
    const output = path.join(root, 'safe output');
    await extractArchiveSafely(archive, output);
    assert.equal(await readFile(path.join(output, 'resources', 'app.asar'), 'utf8'), 'synthetic app payload');
    assert.equal(await realpath(path.join(output, 'resources')), path.join(output, 'resources'));
    assert.throws(() => validateArchivePath('../outside.txt'), /escapes/);
    assert.throws(() => validateArchivePath('C:\\outside.txt'), /escapes/);
    assert.throws(
      () => validateArchiveListing('----------\nPath = link\nSize = 0\nAttributes = A Lrwxrwxrwx\nSymbolic Link = ../../outside\n'),
      /link/i,
    );
    assert.throws(
      () => validateArchiveListing('----------\nPath = one.txt\nSize = 1\n\nPath = ONE.TXT\nSize = 1\n'),
      /duplicate|case-colliding/i,
    );
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test('toolchain integrity ignores only generated Python bytecode caches', async () => {
  const root = await tempDir();
  try {
    const packageFile = path.join(root, 'node-gyp', 'gyp', 'pylib', 'gyp', 'common.py');
    const bytecodeFile = path.join(root, 'node-gyp', 'gyp', 'pylib', 'gyp', '__pycache__', 'common.cpython-312.pyc');
    await mkdir(path.dirname(bytecodeFile), { recursive: true });
    await writeFile(packageFile, 'pinned source');
    await writeFile(bytecodeFile, 'generated bytecode A');
    const firstHash = await hashFilesInTree(root);
    await writeFile(bytecodeFile, 'generated bytecode B');
    assert.equal(await hashFilesInTree(root), firstHash);
    await writeFile(packageFile, 'modified package source');
    assert.notEqual(await hashFilesInTree(root), firstHash);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

