test('desktop rollback restores all active MIME files and refuses intervening changes', async () => {
  const fixture = await createDesktopFixture();
  try {
    const installer = ['python3', path.join(fixture.appRoot, 'scripts/desktop-integration.py')];
    const install = spawnSync(installer[0], [...installer.slice(1), 'install'], { env: fixture.env, encoding: 'utf8' });
    assert.equal(install.status, 0, install.stderr);
    const activeFiles = [
      path.join(fixture.env.XDG_CONFIG_HOME, 'mimeapps.list'),
      path.join(fixture.env.XDG_DATA_HOME, 'applications', 'mimeapps.list'),
      path.join(fixture.env.XDG_CONFIG_HOME, 'gnome-mimeapps.list'),
      path.join(fixture.env.XDG_DATA_HOME, 'applications', 'gnome-mimeapps.list'),
      path.join(fixture.env.XDG_CONFIG_HOME, 'kde-mimeapps.list'),
      path.join(fixture.env.XDG_DATA_HOME, 'applications', 'kde-mimeapps.list'),
    ];
    for (const activeFile of activeFiles) {
      assert.match(await readFile(activeFile, 'utf8'), /factory-desktop-linux\.desktop/);
    }
    const association = path.join(fixture.env.XDG_STATE_HOME, 'factory-desktop-linux/protocol-association/association.json');
    const metadata = JSON.parse(await readFile(association, 'utf8'));
    assert.equal(Object.keys(metadata.after).length, activeFiles.length);

    const changedFile = activeFiles[0];
    await writeFile(changedFile, `${await readFile(changedFile, 'utf8')}# changed after install\n`);
    const refused = spawnSync(installer[0], [...installer.slice(1), 'rollback'], { env: fixture.env, encoding: 'utf8' });
    assert.notEqual(refused.status, 0);
    assert.match(refused.stderr, /changed after installation/);
    assert.ok((await readFile(path.join(fixture.env.XDG_DATA_HOME, 'applications', 'factory-desktop-linux.desktop'), 'utf8'))
      .includes('Factory Desktop'));

    await writeFile(changedFile, Buffer.from(metadata.after[changedFile].content, 'base64'));
    const rollback = spawnSync(installer[0], [...installer.slice(1), 'rollback'], { env: fixture.env, encoding: 'utf8' });
    assert.equal(rollback.status, 0, rollback.stderr);
    for (const activeFile of activeFiles) {
      await assert.rejects(() => readFile(activeFile), { code: 'ENOENT' });
    }
    await assert.rejects(
      () => readFile(path.join(fixture.env.XDG_DATA_HOME, 'applications', 'factory-desktop-linux.desktop')),
      { code: 'ENOENT' },
    );
  } finally {
    await rm(fixture.root, { recursive: true, force: true });
  }
});
